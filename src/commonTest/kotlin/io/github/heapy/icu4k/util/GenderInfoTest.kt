    @Test fun nullAndShortListRulesMatchSource() {
        for(style in GenderInfo.ListGenderStyle.entries) {
            val info=GenderInfo(style)
            assertEquals(GenderInfo.Gender.OTHER,info.getListGender())
            assertNull(info.getListGender(null))
            assertEquals(GenderInfo.Gender.FEMALE,info.getListGender(GenderInfo.Gender.FEMALE))
        }
        assertEquals(GenderInfo.Gender.OTHER,GenderInfo(GenderInfo.ListGenderStyle.NEUTRAL).getListGender(null,null))
        assertEquals(GenderInfo.Gender.MALE,GenderInfo(GenderInfo.ListGenderStyle.MALE_TAINTS).getListGender(null,null))
        assertFailsWith<NullPointerException>{GenderInfo(GenderInfo.ListGenderStyle.MIXED_NEUTRAL).getListGender(null,null)}
        val invalid=GenderInfo(null)
        assertEquals(GenderInfo.Gender.OTHER,invalid.getListGender());assertNull(invalid.getListGender(null))
        assertFailsWith<NullPointerException>{invalid.getListGender(null,null)}
        for((name,style) in listOf("neutral" to GenderInfo.ListGenderStyle.NEUTRAL,"mixedNeutral" to GenderInfo.ListGenderStyle.MIXED_NEUTRAL,"maleTaints" to GenderInfo.ListGenderStyle.MALE_TAINTS))assertEquals(style,GenderInfo.ListGenderStyle.fromName(name))
        assertEquals("Unknown gender style name: null",assertFailsWith<IllegalArgumentException>{GenderInfo.ListGenderStyle.fromName(null)}.message)
    }
