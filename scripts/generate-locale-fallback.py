#!/usr/bin/env python3
"""Generate ICU 78.3 locale parent/script tables from the pinned extracted data."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = root / 'data/locale-fallback.json'
if hashlib.sha256(source.read_bytes()).hexdigest() != '148b4df5980b0108c54acd552f1addbbac815a319e940642e804c464fd188764':
    raise SystemExit('Pinned locale fallback data checksum mismatch')
data = json.loads(source.read_text())
lines = ['// © 2022 and later: Unicode, Inc. and others.', '// SPDX-License-Identifier: Unicode-3.0',
         '// Generated by scripts/generate-locale-fallback.py. Do not edit.',
         f"// ICU 78.3 source commit: {data['upstream_commit']}",
         'package io.github.heapy.icu4k.impl', '',
         'import io.github.heapy.icu4k.impl.locale.localeReadOnlyMap', '',
         'internal object LocaleFallbackData {']
for name, table in data['tables'].items():
    lines.append(f'    val {name}: Map<String, String> = localeReadOnlyMap(mapOf(')
    for key, value in table.items():
        lines.append(f'        {json.dumps(key)} to {json.dumps(value)},')
    lines.append('    ))')
lines.extend(['}', ''])
text = '\n'.join(lines)
output = root / 'src/commonMain/kotlin/io/github/heapy/icu4k/impl/LocaleFallbackData.kt'
if args.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('Generated locale fallback tables are stale')
else:
    output.write_text(text)
print(f"{'Checked' if args.check else 'Generated'} {sum(map(len, data['tables'].values()))} locale fallback entries")
