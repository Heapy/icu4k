#!/usr/bin/env python3
"""Generate Common Kotlin's RBBI grammar table from the pinned ICU rbbirpt.txt."""
import argparse
import hashlib
from pathlib import Path
import shlex

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = root / 'data/compiler/rbbirpt.txt'
if hashlib.sha256(source.read_bytes()).hexdigest() != '3b12b99741b0d71667761d12ca944c5a75309765e254a77897652f50c5b14111':
    raise SystemExit('Pinned RBBI grammar checksum mismatch')
rows = []
states = {'exit': 0, 'pop': 255}
pending_name = None
for raw in source.read_text().splitlines():
    line = raw.split('#', 1)[0].strip()
    if not line:
        continue
    if line.endswith(':'):
        name = line[:-1]
        if name in states:
            raise SystemExit(f'Duplicate state: {name}')
        states[name] = len(rows) + 1
        pending_name = name
        continue
    tokens = shlex.split(line, posix=False)
    char_class = tokens.pop(0)
    consume = tokens[0] == 'n'
    if consume:
        tokens.pop(0)
    next_state = tokens.pop(0)
    push = tokens.pop(0)[1:] if tokens and tokens[0].startswith('^') else None
    action = tokens.pop(0) if tokens else 'doNOP'
    if tokens:
        raise SystemExit(f'Unexpected grammar columns: {line}')
    rows.append((action, char_class, next_state, push, consume, pending_name))
    pending_name = None
actions = {name: i + 1 for i, name in enumerate(sorted({r[0] for r in rows}))}
classes = {'eof': 252, 'escaped': 254, 'default': 255}
classes.update({name: 128 + i for i, name in enumerate(sorted({r[1] for r in rows if not r[1].startswith("'")} - classes.keys()))})
lines = ['// © 2016 and later: Unicode, Inc. and others.', '// SPDX-License-Identifier: Unicode-3.0',
         '// Generated by scripts/generate-rule-parser.py from pinned ICU 78.3 rbbirpt.txt.',
         'package io.github.heapy.icu4k.text', '', 'internal object RBBIRuleParseTable {']
for name, value in actions.items():
    lines.append(f'    const val {name} = {value}')
for name, value in sorted(classes.items()):
    lines.append(f'    const val kRuleSet_{name} = {value}')
lines.extend(['', '    class RBBIRuleTableElement(val fAction: Int, val fCharClass: Int, val fNextState: Int,',
              '                               val fPushState: Int, val fNextChar: Boolean, val fStateName: String?)',
              '    val gRuleParseStateTable = arrayOf(',
              '        RBBIRuleTableElement(doNOP, 0, 0, 0, true, null), // 0'])
for index, (action, cc, ns, ps, consume, name) in enumerate(rows, 1):
    if cc.startswith("'"):
        if len(cc) != 3:
            raise SystemExit(f'Unexpected character literal: {cc}')
        value = ord(cc[1])
    else:
        value = classes[cc]
    state_name = f'"{name}"' if name is not None else 'null'
    lines.append(f'        RBBIRuleTableElement({action}, {value}, {states[ns]}, {states[ps] if ps else 0}, {str(consume).lower()}, {state_name}), // {index}')
lines.extend(['    )', '}', ''])
result = '\n'.join(lines)
output = root / 'src/commonMain/kotlin/io/github/heapy/icu4k/text/RBBIRuleParseTable.kt'
if args.check:
    if not output.exists() or output.read_text() != result:
        raise SystemExit('Generated RBBI grammar table is stale')
else:
    output.write_text(result)
print(f"{'Checked' if args.check else 'Generated'} {len(rows) + 1} RBBI grammar rows, {len(actions)} actions")
