#!/usr/bin/env python3
"""Embed pinned ICU data as portable Base64; no network or JVM required."""
import argparse
import base64
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Verify outputs without writing')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
manifest = json.loads((root / 'data/manifest.json').read_text())
output = root / 'src/commonMain/kotlin/io/github/heapy/icu4k/impl/data'
output.mkdir(parents=True, exist_ok=True)
for resource in manifest['resources']:
    raw = (root / resource['file']).read_bytes()
    if len(raw) != resource['size'] or hashlib.sha256(raw).hexdigest() != resource['sha256']:
        raise SystemExit(f"ICU data checksum mismatch: {resource['file']}")
    encoded = base64.b64encode(raw).decode('ascii')
    lines = [
        '// © 2016 and later: Unicode, Inc. and others.',
        '// SPDX-License-Identifier: Unicode-3.0',
        '// Generated by scripts/generate-data.py. Do not edit.',
        f"// ICU {manifest['tag']}: {resource['name']}; SHA-256 {resource['sha256']}",
        'package io.github.heapy.icu4k.impl.data', '',
        'import kotlin.io.encoding.Base64', '',
        f"internal object {resource['object']} {{",
        '    private val content: ByteArray by lazy {',
        '        Base64.decode(buildString {',
    ]
    for index in range(0, len(encoded), 8192):
        lines.append(f'            append("{encoded[index:index + 8192]}")')
    lines.extend(['        })', '    }', '    fun copy(): ByteArray = content.copyOf()', '}', ''])
    text = '\n'.join(lines)
    path = output / f"{resource['object']}.kt"
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f'Generated ICU data is stale: {path.relative_to(root)}')
    else:
        path.write_text(text)
# Partition directory dispatch to keep platform methods small as locale data grows.
for prefix, registry in manifest.get('registries', {}).items():
    resources = [r for r in manifest['resources'] if r['name'].startswith(prefix)]
    groups = [resources[i:i + 32] for i in range(0, len(resources), 32)]
    lines = [
        '// © 2016 and later: Unicode, Inc. and others.',
        '// SPDX-License-Identifier: Unicode-3.0',
        '// Generated by scripts/generate-data.py. Do not edit.',
        'package io.github.heapy.icu4k.impl.data', '',
        f'internal object {registry} {{',
        '    private val groups: Map<String, Int> = mapOf(',
    ]
    for index, group in enumerate(groups):
        lines.extend(f'        "{r["name"]}" to {index},' for r in group)
    lines.extend(['    )', '    val names: Set<String> get() = groups.keys',
                  '    fun getBytes(name: String): ByteArray? = when (groups[name]) {'])
    for index in range(len(groups)):
        lines.append(f'        {index} -> group{index}(name)')
    lines.extend(['        else -> null', '    }'])
    for index, group in enumerate(groups):
        lines.append(f'    private fun group{index}(name: String): ByteArray? = when (name) {{')
        lines.extend(f'        "{r["name"]}" -> {r["object"]}.copy()' for r in group)
        lines.extend(['        else -> null', '    }'])
    lines.extend(['}', ''])
    text = '\n'.join(lines)
    path = output / f'{registry}.kt'
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f'Generated ICU registry is stale: {path.relative_to(root)}')
    else:
        path.write_text(text)
print(f"{'Checked' if args.check else 'Generated'} {len(manifest['resources'])} ICU resources")
