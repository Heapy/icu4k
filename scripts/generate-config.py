#!/usr/bin/env python3
"""Generate pinned ICU runtime defaults and the JVM classpath properties resource."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = root / 'data/config/ICUConfig.properties'
raw = source.read_bytes()
if hashlib.sha256(raw).hexdigest() != '2f813bd9e6a424673917035bd38f0ec707bbdacb080087512da5f7976ec7dad8':
    raise SystemExit('Pinned ICUConfig.properties checksum mismatch')
properties = {}
for line in raw.decode('ascii').splitlines():
    line = line.strip()
    if not line or line.startswith(('#', '!')):
        continue
    # These pinned entries have no escaping or continuation. JVM custom files use Properties.load.
    if '=' not in line or '\\' in line:
        raise SystemExit('Unexpected pinned configuration syntax')
    key, value = line.split('=', 1)
    properties[key.strip()] = value.strip()
lines = ['// © 2016 and later: Unicode, Inc. and others.', '// SPDX-License-Identifier: Unicode-3.0',
         '// Generated by scripts/generate-config.py from ICU 78.3. Do not edit.',
         'package io.github.heapy.icu4k.impl', '', 'internal object ICUConfigDefaults {',
         '    val properties: Map<String, String> = mapOf(']
for key, value in properties.items():
    lines.append(f'        {json.dumps(key)} to {json.dumps(value)},')
lines.extend(['    )', '}', ''])
outputs = {
    root / 'src/commonMain/kotlin/io/github/heapy/icu4k/impl/ICUConfigDefaults.kt': '\n'.join(lines).encode(),
    root / 'src/jvmMain/resources/com/ibm/icu/ICUConfig.properties': raw,
}
for path, content in outputs.items():
    if args.check:
        if not path.exists() or path.read_bytes() != content:
            raise SystemExit(f'Stale generated configuration: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
print(f"{'Checked' if args.check else 'Generated'} {len(properties)} ICU configuration defaults")
