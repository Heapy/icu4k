#!/usr/bin/env python3
"""Embed pinned ICU4J multibyte detection tables; optionally reimport from upstream."""
import argparse, hashlib, json, re
from pathlib import Path
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--import-upstream', type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
path = root / 'data/charset/mbcs-common-chars.json'
source_path = 'icu4j/main/core/src/main/java/com/ibm/icu/text/CharsetRecog_mbcs.java'
source_sha = '3f425fc0994eb14b1dc608659a48c9b1d8380029081f16eedad93ae6f35f2f7e'
if args.import_upstream:
    raw = (args.import_upstream / source_path).read_bytes()
    if hashlib.sha256(raw).hexdigest() != source_sha:
        raise SystemExit('Pinned ICU4J MBCS source checksum mismatch')
    text = re.sub(r'//[^\n]*|/\*[\s\S]*?\*/', '', raw.decode())
    arrays = re.findall(r'static\s+int\s*\[\]\s*commonChars\s*=\s*\{([^}]+)\}', text)
    if len(arrays) != 5:
        raise SystemExit('Expected five MBCS tables')
    imported = {'source': source_path, 'source_sha256': source_sha, 'tables': {
        name: [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body)]
        for name, body in zip(['sjis','big5','euc_jp','euc_kr','gb_18030'], arrays)}}
    content = json.dumps(imported, indent=2)+'\n'
    if args.check:
        if path.read_text() != content: raise SystemExit('Imported MBCS tables are stale')
    else:
        path.write_text(content)
raw = path.read_bytes()
if hashlib.sha256(raw).hexdigest() != '51670075ebd3189729c141ff1bcdb7dda9688f040c04e7971245e3763e265d9c':
    raise SystemExit('Pinned MBCS table checksum mismatch')
data = json.loads(raw)
lines = ['// © 2016 and later: Unicode, Inc. and others.',
         '// Copyright (C) 2005-2012, International Business Machines Corporation and others. All Rights Reserved.',
         '// SPDX-License-Identifier: Unicode-3.0',
         '// Generated by scripts/generate-charset-mbcs.py from ICU4J 78.3. Do not edit.',
         'package io.github.heapy.icu4k.text', '', 'internal object CharsetMbcsTables {']
for name, values in data['tables'].items():
    lines.append(f'    val {name} = intArrayOf(')
    for offset in range(0,len(values),10):
        lines.append('        '+','.join(f'0x{value:04x}' for value in values[offset:offset+10])+',')
    lines.append('    )')
lines.extend(['}', ''])
output = root / 'src/commonMain/kotlin/io/github/heapy/icu4k/text/CharsetMbcsTables.kt'
content = '\n'.join(lines)
if args.check:
    if output.read_text() != content: raise SystemExit('Generated MBCS tables are stale')
else:
    output.write_text(content)
print(('Checked' if args.check else 'Generated')+' five MBCS frequency tables')
