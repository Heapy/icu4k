#!/usr/bin/env python3
"""Generate all pinned ICU4J 78.3 single-byte charset models and recognizer definitions."""
import argparse,re,json,hashlib
from pathlib import Path
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
parser.add_argument('--import-upstream',type=Path)
args=parser.parse_args()
root=Path(__file__).resolve().parent.parent
path=root/'data/charset/sbcs.json'
if args.import_upstream:
    p=args.import_upstream/'icu4j/main/core/src/main/java/com/ibm/icu/text/CharsetRecog_sbcs.java'
    if hashlib.sha256(p.read_bytes()).hexdigest() != '26b2d2483b19e23e89d00fee9908ad877002078c79569aac4c567bcaa13525d1':
        raise SystemExit('Pinned SBCS source checksum mismatch')
    s=re.sub(r'//[^\n]*|/\*[\s\S]*?\*/','',p.read_text())
    classes={}
    for m in re.finditer(r'(abstract\s+)?static\s+class\s+(CharsetRecog_\w+)\s+extends\s+(\w+)\s*\{',s):
     start=m.end();depth=1;i=start
     while depth:
      if s[i]=='{':depth+=1
      if s[i]=='}':depth-=1
      i+=1
     body=s[start:i-1]; fields={}
     for a in re.finditer(r'(?:byte|int)\s*\[\]\s*(\w+)\s*=\s*\{([^}]+)\}',body):
      fields[a[1]]=[int(v,16) for v in re.findall(r'0x[0-9a-fA-F]+',a[2])]
     langs=[]
     for a in re.finditer(r'new NGramsPlusLang\(\s*"(\w+)"\s*,\s*new int\s*\[\]\s*\{([^}]+)\}',body):
      langs.append([a[1],[int(v,16) for v in re.findall(r'0x[0-9a-fA-F]+',a[2])]])
     def ret(method):
      a=re.search(r'public String '+method+r'\(\)\s*\{\s*return\s+"([^"]+)"',body)
      return a[1] if a else None
     alias=re.search(r'fC1Bytes\s*\?\s*"([^"]+)"',body)
     classes[m[2]]={'parent':m[3],'abstract':bool(m[1]),'fields':fields,'languages':langs,'name':ret('getName'),'language':ret('getLanguage'),'alias':alias[1] if alias else None}
    a=re.search(r'byte\s*\[\]\s*unshapeMap\s*=\s*\{([^}]+)\}',s)
    d={'source_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'classes':classes,'unshape':[int(v,16) for v in re.findall(r'0x[0-9a-fA-F]+',a[1])]}
    content=json.dumps(d,indent=2)+'\n'
    if args.check:
        if path.read_text()!=content: raise SystemExit('Imported SBCS tables are stale')
    else: path.write_text(content)
raw=path.read_bytes()
if hashlib.sha256(raw).hexdigest()!='a179084552f1610c568b58e5831ca5829d49e9967a7c6baccdd07140dbc07238':
    raise SystemExit('Pinned SBCS data checksum mismatch')
d=json.loads(raw)
classes=d['classes']
lines=['// © 2016 and later: Unicode, Inc. and others.',
       '// Copyright (C) 2005-2012, International Business Machines Corporation and others. All Rights Reserved.',
       '// SPDX-License-Identifier: Unicode-3.0',
       '// Generated by scripts/generate-charset-sbcs.py from ICU4J 78.3. Do not edit.',
       'package io.github.heapy.icu4k.text','','internal object CharsetSbcsTables {']
def array(name,values,size):
    assert len(values)==size
    lines.append(f'    val {name} by lazy {{ intArrayOf(')
    for i in range(0,len(values),10):
        lines.append('        '+','.join(hex(x) for x in values[i:i+10])+',')
    lines.append('    ) }')
array('unshape',d['unshape'],256)
for key,c in classes.items():
    for field,values in c['fields'].items():
        if field=='ngrams': assert values==sorted(set(values))
        array(key+'_'+field,values,256 if field=='byteMap' else 64)
    for lang,values in c['languages']:
        assert values==sorted(set(values))
        array(key+'_'+lang,values,64)
def inherited(key,field):
    c=classes[key]
    if c.get(field) is not None: return c[field]
    return inherited(c['parent'],field) if c['parent'] in classes else None
def map_name(key):
    if 'byteMap' in classes[key]['fields']: return key+'_byteMap'
    return map_name(classes[key]['parent'])
def literal(x): return 'null' if x is None else json.dumps(x)
lines+=['','    fun recognizers(): List<CharsetRecog_sbcs> = listOf(']
for key,c in classes.items():
    if c['abstract']: continue
    language=inherited(key,'language') if not c['languages'] else None
    models= [(lang,key+'_'+lang) for lang,values in c['languages']] if c['languages'] else [(language,key+'_ngrams')]
    models='listOf('+','.join(literal(lang)+' to '+table for lang,table in models)+')'
    lines.append('        CharsetRecog_sbcs('+','.join([literal(inherited(key,'name')),literal(language),map_name(key),models,literal(c['alias']),str('IBM420' in key).lower(), '0x40' if 'IBM' in key else '0x20'])+'),')
lines+=['    )','}', '']
output=root/'src/commonMain/kotlin/io/github/heapy/icu4k/text/CharsetSbcsTables.kt'
content='\n'.join(lines)
if args.check:
    if output.read_text()!=content: raise SystemExit('Generated SBCS models are stale')
else: output.write_text(content)
print(('Checked' if args.check else 'Generated')+' all 15 SBCS recognizers and 27 language models')
