#!/usr/bin/env python3
"""Generate the exact pinned ICU4J CollationFCD bitmaps as Common Kotlin arrays."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = root / 'data/collation-fcd.json'
if hashlib.sha256(source.read_bytes()).hexdigest() != '7b02ea0925f94c261b57cc64641aa175fe29474d1f9818c40c02e5fb49e38990':
    raise SystemExit('Pinned collation FCD data checksum mismatch')
data = json.loads(source.read_text())
manifest = json.loads((root / 'data/manifest.json').read_text())
if data['upstream_commit'] != manifest['commit'] or data['upstream_tag'] != manifest['tag']:
    raise SystemExit('Collation FCD data and ICU resource revisions differ')
lines = ['// © 2016 and later: Unicode, Inc. and others.',
         '// Copyright (C) 2012-2016, International Business Machines Corporation and others.',
         '// SPDX-License-Identifier: Unicode-3.0',
         '// Generated by scripts/generate-collation-fcd.py. Do not edit.',
         f"// ICU 78.3 source SHA-256: {data['source_sha256']}",
         'package io.github.heapy.icu4k.impl.coll', '', 'internal object CollationFCDData {']
for name, table in data['tables'].items():
    kind = 'Byte' if table['type'] == 'byte' else 'Int'
    values = table['values']
    lines.append(f'    val {name}: {kind}Array = {kind.lower()}ArrayOf(')
    for offset in range(0, len(values), 16):
        lines.append('        ' + ', '.join(map(str, values[offset:offset + 16])) + ',')
    lines.append('    )')
lines.extend(['}', ''])
text = '\n'.join(lines)
output = root / 'src/commonMain/kotlin/io/github/heapy/icu4k/impl/coll/CollationFCDData.kt'
if args.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('Generated collation FCD bitmaps are stale')
else:
    output.write_text(text)
print(f"{'Checked' if args.check else 'Generated'} {sum(len(t['values']) for t in data['tables'].values())} collation FCD entries")
